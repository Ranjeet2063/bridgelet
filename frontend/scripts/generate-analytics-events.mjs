#!/usr/bin/env node
/**
 * Generates the single source-of-truth TypeScript union for all analytics
 * event names defined in `docs/analytics-spec.md` §4-6.
 *
 * Issue #677 — concrete first step toward the CI drift-check recommended in
 * `bridgelet-product-audit/postmortems/analytics-spec-vs-implementation-unverified.md`.
 *
 * Source: `#### \`Event Name\`` headings found between `## 4.` (Sender Journey)
 * and `## 7.` (Conversion Funnels). Sections 7-9 mention event names in funnel
 * tables/code fences but do not define events, so they are excluded.
 *
 * Usage:
 *   npm run generate:analytics-events
 *
 * Output (checked in):
 *   frontend/lib/analytics-events.ts
 *   - `ANALYTICS_EVENTS` const tuple (spec order)
 *   - `ANALYTICS_EVENT_NAMES` Set-backed readonly list + `isAnalyticsEventName` guard
 *   - `AnalyticsEventName` union type referenced by `frontend/lib/analytics.ts`
 *
 * CI (`.github/workflows/analytics-spec-diff.yml`) fails when the generated
 * file is stale. Run this script after editing the spec and commit the result.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..', '..');
const specPath = resolve(repoRoot, 'docs', 'analytics-spec.md');
const outPath = resolve(here, '..', 'lib', 'analytics-events.ts');

const text = readFileSync(specPath, 'utf8');
const lines = text.split(/\r?\n/);

let section = null;
const events = [];
for (const line of lines) {
  const sectionMatch = line.match(/^##\s+(\d+)\./);
  if (sectionMatch) section = Number.parseInt(sectionMatch[1], 10);
  const headingMatch = line.match(/^####\s+`([^`]+)`/);
  if (headingMatch && section !== null && section >= 4 && section <= 6) {
    const name = headingMatch[1].trim();
    if (name.length > 0 && !events.includes(name)) events.push(name);
  }
}

if (events.length === 0) {
  console.error(`No events found in ${specPath} (Sections 4-6). Refusing to write empty union.`);
  process.exit(1);
}

const EXPECTED_COUNT = 34;
if (events.length !== EXPECTED_COUNT) {
  console.error(
    `Expected ${EXPECTED_COUNT} spec events (Sections 4-6) but found ${events.length} in ${specPath}. ` +
      `Update EXPECTED_COUNT in this script and in lib/analytics-events.test.ts if the spec intentionally changed.`,
  );
  console.error(JSON.stringify(events, null, 2));
  process.exit(1);
}

const literalList = events.map((e) => `  '${e.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n');

const output = `// AUTO-GENERATED by frontend/scripts/generate-analytics-events.mjs — do not edit manually.
// Source: docs/analytics-spec.md Sections 4-6 (\`#### \\\`Event Name\\\`\` headings).
// Run \`npm run generate:analytics-events\` after editing the spec and commit the result.
// Issue #677: single source-of-truth for all ${EXPECTED_COUNT} spec event names.

/** All ${EXPECTED_COUNT} event names from docs/analytics-spec.md Sections 4-6, in spec order. */
export const ANALYTICS_EVENTS = [
${literalList}
] as const;

/** Union of all spec event names. Referenced by frontend/lib/analytics.ts. */
export type AnalyticsEventName = (typeof ANALYTICS_EVENTS)[number];

/** Set-backed lookup for runtime validation / tests. */
export const ANALYTICS_EVENT_NAMES: ReadonlySet<AnalyticsEventName> = new Set(ANALYTICS_EVENTS);

/** Runtime guard: true when value is one of the ${EXPECTED_COUNT} spec event names. */
export function isAnalyticsEventName(value: unknown): value is AnalyticsEventName {
  return typeof value === 'string' && ANALYTICS_EVENT_NAMES.has(value as AnalyticsEventName);
}

/** Expected spec event count. Bump together with the generator when the spec intentionally changes. */
export const ANALYTICS_EVENT_COUNT = ${EXPECTED_COUNT} as const;
`;

writeFileSync(outPath, output);
console.log(`Wrote ${events.length} event names to ${outPath}`);
